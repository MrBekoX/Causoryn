interface Shape {
  readonly name: string;
  readonly root: string;
  readonly nestedDir: string;
}

const shapes: Shape[] = [];

function makeShape(name: string, levels: readonly [number, number, number], gitignore: string, nestedAt: string): Shape {
  const tree = makeTree(`causoryn-ign-shape-${name}-`, ...levels);
  writeFileSync(path.join(tree.root, ".gitignore"), gitignore, "utf8");
  // A .NET project (smart bin/ split) and a Node bin/ source next to it.
  mkdirSync(path.join(tree.root, areaName(0), "dotnet-app"), { recursive: true });
  writeFileSync(path.join(tree.root, areaName(0), "dotnet-app", "App.csproj"), "<Project />\n", "utf8");
  mkdirSync(path.join(tree.root, "bin"), { recursive: true });
  writeFileSync(path.join(tree.root, "bin", "cli.ts"), "export {};\n", "utf8");
  // A nested .gitignore late in the walk (breadth first, by name).
  writeFileSync(path.join(tree.root, ...nestedAt.split("/"), ".gitignore"), "local-secrets.yml\n", "utf8");
  return { name, root: tree.root, nestedDir: nestedAt };
}

beforeAll(() => {
  // 12 + 12*12 + 12*12*10 = 1,596 directories (the reviewer's 1,554-directory shape).
  shapes.push(makeShape("150-lines", [12, 12, 10], typicalGitignore(150), `${areaName(11)}/${moduleName(11)}`));
  shapes.push(makeShape("visualstudio-400-lines", [12, 12, 10], visualStudioLikeGitignore(), `${areaName(11)}/${moduleName(11)}`));
  // 18 + 18*18 + 18*18*14 = 4,878 directories; the walk visits at most 4,000.
  shapes.push(makeShape("50-lines-4680-dirs", [18, 18, 14], typicalGitignore(50), `${areaName(17)}/${moduleName(17)}`));
}, 180_000);

const ONE_TENTH = {
  maxMatchWork: Math.floor(MAX_DISCOVERY_MATCH_WORK / 10),
  maxNegationWork: Math.floor(MAX_DISCOVERY_NEGATION_WORK / 10),
  maxDirectoryEntries: Math.floor(MAX_DISCOVERY_DIRECTORY_ENTRIES / 10),
};

describe("ignore discovery — realistic repositories stay within the budgets (F46 / F49 round 2)", () => {
  for (const shapeName of ["150-lines", "visualstudio-400-lines", "50-lines-4680-dirs"]) {
    it(`${shapeName}: no budget is reached, nested .gitignore files are found and the smart bin/ split applies`, () => {
      const shape = shapes.find((candidate) => candidate.name === shapeName) as Shape;
      const result = discoverWorkspaceIgnoreConfig(shape.root);
      expect(result.limitReached, shapeName).toBeUndefined();
      expect(result.extraIgnore, shapeName).toContain(`${shape.nestedDir}/**/local-secrets.yml`);
      expect(result.refinedDefaultIgnore, shapeName).toBeDefined();
      expect(result.refinedDefaultIgnore, shapeName).not.toContain("**/bin/**");
      expect(result.refinedDefaultIgnore, shapeName).toContain("**/bin/Debug/**");
      expect(result.refinedDefaultIgnore, shapeName).toContain(`${areaName(0)}/dotnet-app/bin/**`);
    });

    it(`${shapeName}: fits in one tenth of every default budget, with the same result`, () => {
      const shape = shapes.find((candidate) => candidate.name === shapeName) as Shape;
      const tight = discoverWorkspaceIgnoreConfig(shape.root, { budgets: ONE_TENTH });
      expect(tight.limitReached, shapeName).toBeUndefined();
      expect(tight).toEqual(discoverWorkspaceIgnoreConfig(shape.root));
    });
  }
});
