import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

import { afterAll, beforeAll, describe, expect, it } from "vitest";

import {
  MAX_DISCOVERY_DIRECTORY_ENTRIES,
  MAX_DISCOVERY_MATCH_WORK,
  MAX_DISCOVERY_NEGATION_WORK,
  discoverWorkspaceIgnoreConfig,
} from "../src/workspace-ignore-discovery.js";

/**
 * F46 / F49 round 2: the total work budgets of ignore discovery must charge the
 * work the matcher really does, so realistic repositories use a small fraction
 * of them. Each shape below is generated as a real directory tree and run
 * through the real discoverWorkspaceIgnoreConfig:
 * - 1,554 directories with a 150-line .gitignore,
 * - 1,554 directories with a 400-line, VisualStudio.gitignore-sized file
 *   (bracket classes, extension globs, globstar directories and negations),
 * - 4,680 directories with a 50-line .gitignore.
 * None may reach a budget: the nested .gitignore files are still found and
 * the smart `bin/` split (refinedDefaultIgnore, AC-4) still replaces the
 * coarse `**\/bin/**`, so Node `bin/cli.ts` and Rust `src/bin/` stay indexed.
 */

const roots: string[] = [];
afterAll(() => {
  for (const dir of roots.splice(0)) rmSync(dir, { recursive: true, force: true, maxRetries: 10, retryDelay: 100 });
});

/** Realistic-length directory names (a feature area, a module, its parts). */
function areaName(index: number): string {
  return `area${String(index).padStart(2, "0")}-feature-service`;
}
function moduleName(index: number): string {
  return `module${String(index).padStart(2, "0")}-domain-handlers`;
}

/** A three-level tree of `l1 * l2 * l3` leaf directories plus their parents. */
function makeTree(prefix: string, l1: number, l2: number, l3: number): { readonly root: string; readonly dirCount: number } {
  const base = mkdtempSync(path.join(tmpdir(), prefix));
  roots.push(base);
  const root = path.join(base, "repo");
  let dirCount = 0;
  for (let a = 0; a < l1; a += 1) {
    for (let b = 0; b < l2; b += 1) {
      for (let c = 0; c < l3; c += 1) {
        mkdirSync(path.join(root, areaName(a), moduleName(b), `part-${String(c).padStart(2, "0")}-components`), {
          recursive: true,
        });
        dirCount += 1;
      }
      dirCount += 1;
    }
    dirCount += 1;
  }
  return { root, dirCount };
}

/** A .gitignore of `lines` typical entries (the shapes of the common templates, two negations). */
function typicalGitignore(lines: number): string {
  const out: string[] = ["# generated", "!.env.example", "!keep-this-generated-file.json"];
  const kinds = [
    (i: number) => `*.generated-ext${String(i)}`,
    (i: number) => `build-output-${String(i)}/`,
    (i: number) => `/root-artifact-${String(i)}`,
    (i: number) => `**/coverage-report-cache-${String(i)}/**`,
    (i: number) => `logs/**/*.debug-log${String(i)}`,
    (i: number) => `npm-debug-${String(i)}.log*`,
    (i: number) => `.env.*.local${String(i)}`,
    (i: number) => `**/*.tsbuildinfo${String(i)}`,
  ];
  for (let i = 0; out.length <= lines; i += 1) {
    out.push((kinds[i % kinds.length] as (i: number) => string)(i));
  }
  return out.join("\n");
}

