const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const IS_WIN = process.platform === "win32";

const cleanup: string[] = [];
afterAll(() => {
  for (const dir of cleanup) rmSync(dir, { recursive: true, force: true });
});

function tempDir(prefix: string): string {
  const dir = realpathSync.native(mkdtempSync(path.join(os.tmpdir(), prefix)));
  cleanup.push(dir);
  return dir;
}

function fakeChild(
  options: { pid?: number | undefined; responseLine?: string; exitCode?: number } = {},
): ChildProcess {
  const child = new EventEmitter() as unknown as ChildProcess;
  const record = child as unknown as Record<string, unknown>;
  record["stdout"] = new EventEmitter();
  record["stderr"] = new EventEmitter();
  record["stdin"] = Object.assign(new EventEmitter(), { write: () => true, end: () => {} });
  record["pid"] = options.pid;
  record["killed"] = false;
  record["exitCode"] = null;
  record["signalCode"] = null;
  record["kill"] = () => {
    record["killed"] = true;
    return true;
  };
  queueMicrotask(() => {
    if (options.responseLine !== undefined) {
      (record["stdout"] as EventEmitter).emit("data", Buffer.from(`${options.responseLine}\n`, "utf8"));
    } else if (options.exitCode !== undefined) {
      child.emit("exit", options.exitCode, null);
    }
  });
  return child;
}

async function withEnv<T>(
  overrides: Readonly<Record<string, string | undefined>>,
  fn: () => Promise<T> | T,
): Promise<T> {
  const saved = new Map<string, string | undefined>();
  for (const [key, value] of Object.entries(overrides)) {
    saved.set(key, process.env[key]);
    if (value === undefined) delete process.env[key];
    else process.env[key] = value;
  }
  try {
    return await fn();
  } finally {
    for (const [key, value] of saved) {
      if (value === undefined) delete process.env[key];
      else process.env[key] = value;
    }
  }
}

/** Minimal dependency-free stand-in for native/rust-worker (answers one request). */
function stageMinimalRustCrate(crateDir: string): string {
  mkdirSync(path.join(crateDir, "src"), { recursive: true });
  writeFileSync(
    path.join(crateDir, "Cargo.toml"),
    '[package]\nname = "causoryn-rust-worker"\nversion = "0.1.0"\nedition = "2021"\n\n[dependencies]\n',
    "utf8",
  );
  writeFileSync(
    path.join(crateDir, "Cargo.lock"),
    '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "causoryn-rust-worker"\nversion = "0.1.0"\n',
    "utf8",
  );
  writeFileSync(
    path.join(crateDir, "src", "main.rs"),
    [
      "use std::io::{self, BufRead, Write};",
      "fn main() {",
      "    let mut line = String::new();",
      "    let _ = io::stdin().lock().read_line(&mut line);",
      '    let id = line.split("\\"id\\":\\"").nth(1).and_then(|r| r.split(\'"\').next()).unwrap_or("analyze:unknown").to_string();',
      '    let out = format!("{{\\"id\\":\\"{}\\",\\"protocolVersion\\":\\"1\\",\\"status\\":\\"ready\\",\\"coverageRatio\\":1.0,\\"capabilities\\":{{\\"astParse\\":true,\\"symbolResolution\\":true,\\"containsEdges\\":true,\\"callEdges\\":true,\\"importEdges\\":false,\\"routeDetection\\":\\"none\\",\\"frameworkLinkers\\":false}},\\"unsupportedConstructs\\":[],\\"warnings\\":[],\\"diagnostics\\":[],\\"nodes\\":[],\\"edges\\":[],\\"evidence\\":[]}}\\n", id);',
      "    let _ = io::stdout().write_all(out.as_bytes());",
      "    let _ = io::stdout().flush();",
      "}",
      "",
    ].join("\n"),
    "utf8",
  );
  return path.join(crateDir, "Cargo.toml");
}

/** Hostile cargo / rustup config in the analyzed repository root. */
function plantHostileCargoConfig(repo: string, markerFile: string): void {
  const script = IS_WIN ? path.join(repo, "evil-tool.cmd") : path.join(repo, "evil-tool.sh");
  if (IS_WIN) {
    writeFileSync(script, `@echo off\r\necho pwned > "${markerFile}"\r\nexit /b 1\r\n`, "utf8");
  } else {
    writeFileSync(script, `#!/bin/sh\necho pwned > "${markerFile}"\nexit 1\n`, { encoding: "utf8", mode: 0o755 });
  }
  const escaped = script.replace(/\\/g, "\\\\");
  let host = "";
  const rustc = resolveExecutable("rustc");
  if (rustc !== null) {
    const info = spawnSync(rustc, ["-vV"], { encoding: "utf8", shell: false, windowsHide: true, cwd: os.tmpdir() });
    host = /^host:\s*(\S+)/m.exec(info.stdout ?? "")?.[1] ?? "";
  }
  mkdirSync(path.join(repo, ".cargo"), { recursive: true });
  writeFileSync(
    path.join(repo, ".cargo", "config.toml"),
    [
      "[build]",
      `rustc = "${escaped}"`,
      `rustc-wrapper = "${escaped}"`,
      `rustc-workspace-wrapper = "${escaped}"`,
      ...(host.length > 0 ? ["", `[target.${host}]`, `linker = "${escaped}"`] : []),
      "",
    ].join("\n"),
    "utf8",
  );
  writeFileSync(path.join(repo, "rust-toolchain.toml"), '[toolchain]\nchannel = "nonexistent-hostile-channel-999"\n', "utf8");
}

describe("sidecar workers start by absolute path with a trusted cwd", () => {
  it("python, dotnet and go workers receive absolute commands outside the analyzed workspace", async () => {
    const workspace = tempDir("causoryn-spawn-ws-");
    const captured: Array<{ command: string; cwd: string | undefined }> = [];
    const capture = (command: string, _args: readonly string[], opts: { readonly cwd?: string }): ChildProcess => {
      captured.push({ command, cwd: opts.cwd });
      return fakeChild({ responseLine: '{"id":"x","protocolVersion":"1","status":"ready"}' });
    };
    await withCwdSearchUnmasked(workspace, async () => {
      const python = resolveExecutable("python") ?? resolveExecutable("python3");
      if (python !== null) {
        await runPythonWorkerAnalyze({
          pythonCommand: path.basename(python).replace(/\.exe$/i, ""),
          workerScriptPath: path.join(REPO_ROOT, "native", "python-worker", "worker.py"),
          requestPayload: { id: "x" },
          requestTimeoutMs: 5_000,
          spawnProcess: capture,
        });
      }
      if (resolveExecutable("dotnet") !== null) {
        await runRoslynWorkerAnalyze({
          dotnetCommand: "dotnet",
          workerDllPath: path.join(REPO_ROOT, "native", "roslyn-worker", "Causoryn.RoslynWorker.dll"),
          requestPayload: { id: "x" },
          requestTimeoutMs: 5_000,
          spawnProcess: capture,
        });
      }
      if (resolveExecutable("go") !== null) {
        await runGoWorkerAnalyze({
          goBinaryPath: "go",
          goWorkerBinaryPath: "",
          workerDir: path.join(REPO_ROOT, "native", "go-worker"),
          requestPayload: { id: "x" },
          requestTimeoutMs: 5_000,
          spawnProcess: capture,
        });
      }
    });
    expect(captured.length).toBeGreaterThan(0);
    for (const call of captured) {
      expect(path.isAbsolute(call.command)).toBe(true);
      expect(isWithinUntrustedRoots(call.command, [workspace])).toBe(false);
      expect(call.cwd).toBeDefined();
      expect(isWithinUntrustedRoots(call.cwd!, [workspace])).toBe(false);
    }
  });

  it("a bare worker command that cannot be resolved outside the workspace is refused without spawning", async () => {
    let spawned = false;
    const outcome = await runPythonWorkerAnalyze({
      pythonCommand: "causoryn-missing-python-xyz",
      workerScriptPath: path.join(REPO_ROOT, "native", "python-worker", "worker.py"),
      requestPayload: { id: "x" },
      requestTimeoutMs: 5_000,
      spawnProcess: () => {
        spawned = true;
        return fakeChild({ exitCode: 1 });
      },
    });
    expect(spawned).toBe(false);
    expect(outcome.status).toBe("unavailable");
    expect(outcome.detail).toContain("causoryn-missing-python-xyz");
    expect(outcome.detail).toContain("not found");
  });

  it("the Rust worker binary is started by its absolute path", async () => {
    const workerDir = path.join(REPO_ROOT, "native", "rust-worker", "target", "debug");
    const commands: string[] = [];
    await runRustWorkerAnalyze({
      workerDir,
      workerBinaryName: WORKER_BINARY_NAME,
      requestPayload: { id: "x" },
      requestTimeoutMs: 5_000,
      spawnProcess: (command) => {
        commands.push(command);
        return fakeChild({ responseLine: '{"id":"x","protocolVersion":"1","status":"ready"}' });
      },
    });
    expect(commands).toEqual([path.join(workerDir, WORKER_BINARY_NAME)]);
  });
});

describe("taskkill is always %SystemRoot%\\System32\\taskkill.exe", () => {
  const expectedTaskkill = resolveWindowsSystemExecutable("taskkill.exe");

  it.skipIf(!IS_WIN)("go run tree-kill spawns the absolute taskkill with a trusted cwd", async () => {
    const workspace = tempDir("causoryn-taskkill-ws-");
    const spawned: Array<{ command: string; args: readonly string[]; cwd: string | undefined }> = [];
    await withCwdSearchUnmasked(workspace, async () => {
      const outcome = await runGoWorkerAnalyze({
        goBinaryPath: process.execPath,
        goWorkerBinaryPath: "",
        workerDir: path.join(REPO_ROOT, "native", "go-worker"),
        requestPayload: { id: "tree-kill" },
        requestTimeoutMs: 200,
        spawnProcess: (command, args, opts) => {
          spawned.push({ command, args: [...args], cwd: opts.cwd });
          return fakeChild({ pid: 4242 });
        },
      });
      expect(outcome.status).toBe("timeout");
    });
    expect(spawned).toHaveLength(2);
    expect(spawned[1]?.command).toBe(expectedTaskkill);
    expect(spawned[1]?.args).toEqual(["/pid", "4242", "/T", "/F"]);
    expect(spawned[1]?.cwd).toBe(path.dirname(expectedTaskkill));
  });

  it.skipIf(!IS_WIN)("cargo build timeout tree-kill spawns the absolute taskkill; cargo itself is absolute too", async () => {
    const crate = tempDir("causoryn-taskkill-crate-");
    const manifestPath = stageMinimalRustCrate(crate);
    const spawned: Array<{ command: string; cwd: string | undefined }> = [];
    const outcome = await runCargoBuild({
      manifestPath,
      targetDir: path.join(crate, "target"),
      timeoutMs: 150,
      cargoExecutable: process.execPath,
      spawnFn: (command, _args, opts) => {
        spawned.push({ command, cwd: opts.cwd });
        return fakeChild({ pid: command === process.execPath ? 7777 : undefined });
      },
    });
    expect(outcome.status).toBeNull();
    expect(spawned).toHaveLength(2);
    expect(spawned[0]?.command).toBe(process.execPath);
    expect(spawned[0]?.cwd).toBe(crate);
    expect(spawned[1]?.command).toBe(expectedTaskkill);
    expect(spawned[1]?.cwd).toBe(path.dirname(expectedTaskkill));
  });

  const marker = IS_WIN ? buildMarkerExecutable() : null;
  it.skipIf(marker === null)(
    "a taskkill.exe planted in the analyzed repository root is never started by the go tree-kill",
    async () => {
      const workspace = tempDir("causoryn-taskkill-real-");
      const fakeGoDir = tempDir("causoryn-fake-go-worker-");
      // `node run ./cmd/worker` with cwd = fakeGoDir runs this file and hangs,
      // so the request times out and the tree-kill path executes for real.
      writeFileSync(path.join(fakeGoDir, "run"), "setTimeout(() => {}, 60000);\n", "utf8");
      const planted = plantMarkers(marker!, workspace, ["taskkill"]);
      await withCwdSearchUnmasked(workspace, async () => {
        const outcome = await runGoWorkerAnalyze({
          goBinaryPath: process.execPath,
          goWorkerBinaryPath: "",
          workerDir: fakeGoDir,
          requestPayload: { id: "tree-kill-real" },
          requestTimeoutMs: 1_500,
        });
        expect(outcome.status).toBe("timeout");
        await new Promise((resolve) => setTimeout(resolve, 1_500));
      });
      expect(startedMarkers(planted)).toEqual([]);
    },
    240_000,
  );
});

