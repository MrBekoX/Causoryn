describe("Rust worker builds from a staged crate copy outside the analyzed workspace", () => {
  it("cargo runs in the staged directory with --locked, --manifest-path and --target-dir inside it", async () => {
    const repo = tempDir("causoryn-b2-repo-");
    const sourceManifest = stageMinimalRustCrate(path.join(repo, "node_modules", "causoryn", "native", "rust-worker"));
    const cacheRoot = tempDir("causoryn-b2-cache-");
    const calls: Array<{ command: string; args: readonly string[]; cwd: string | undefined; env: Readonly<Record<string, string>>; stagedFiles: boolean }> = [];
    const outcome = await buildRustWorkerFromStagedSource({
      sourceManifestPath: sourceManifest,
      cacheRoot,
      destinationBinaryPath: path.join(cacheRoot, "debug", WORKER_BINARY_NAME),
      untrustedRoots: [repo],
      timeoutMs: 5_000,
      cargoExecutable: process.execPath,
      spawnFn: (command, args, opts) => {
        const cwd = opts.cwd ?? "";
        calls.push({
          command,
          args,
          cwd: opts.cwd,
          env: opts.env,
          stagedFiles:
            existsSync(path.join(cwd, "Cargo.toml")) &&
            existsSync(path.join(cwd, "Cargo.lock")) &&
            existsSync(path.join(cwd, "src", "main.rs")),
        });
        return fakeChild({ exitCode: 0 });
      },
    });
    expect(calls).toHaveLength(1);
    const call = calls[0]!;
    expect(call.cwd).toBeDefined();
    const stagedDir = call.cwd!;
    expect(isWithinUntrustedRoots(stagedDir, [repo])).toBe(false);
    expect(isWithinUntrustedRoots(stagedDir, [cacheRoot])).toBe(true);
    expect(call.stagedFiles).toBe(true);
    expect(call.command).toBe(process.execPath);
    expect(call.args).toContain("--locked");
    const manifestIndex = call.args.indexOf("--manifest-path");
    expect(call.args[manifestIndex + 1]).toBe(path.join(stagedDir, "Cargo.toml"));
    const targetIndex = call.args.indexOf("--target-dir");
    expect(call.args[targetIndex + 1]).toBe(path.join(stagedDir, "target"));
    expect(call.env["CARGO_BUILD_RUSTC_WRAPPER"]).toBe("");
    expect(call.env["RUSTC_WRAPPER"]).toBe("");
    // The fake build produced no binary: reported honestly, not as success.
    expect(outcome.ok).toBe(false);
    expect(outcome.detail).toContain("binary");
    // The per-build staging directory is removed afterwards.
    expect(existsSync(stagedDir)).toBe(false);
  });

  it("refuses to build when the cache directory is inside the analyzed workspace", async () => {
    const repo = tempDir("causoryn-b2-refuse-");
    const sourceManifest = stageMinimalRustCrate(path.join(repo, "node_modules", "causoryn", "native", "rust-worker"));
    let spawned = false;
    const outcome = await buildRustWorkerFromStagedSource({
      sourceManifestPath: sourceManifest,
      cacheRoot: path.join(repo, ".causoryn-cache"),
      destinationBinaryPath: path.join(repo, ".causoryn-cache", "debug", WORKER_BINARY_NAME),
      untrustedRoots: [repo],
      timeoutMs: 5_000,
      cargoExecutable: process.execPath,
      spawnFn: () => {
        spawned = true;
        return fakeChild({ exitCode: 0 });
      },
    });
    expect(spawned).toBe(false);
    expect(outcome.ok).toBe(false);
    expect(outcome.detail).toContain("inside the analyzed workspace");
    expect(existsSync(path.join(repo, ".causoryn-cache"))).toBe(false);
  });

  it("analyzeRustWorkspace reports the Rust analyzer unavailable (English diagnostic) when the cache is inside the workspace", async () => {
    const repo = tempDir("causoryn-b2-analyzer-refuse-");
    const assetRoot = path.join(repo, "node_modules", "causoryn");
    stageMinimalRustCrate(path.join(assetRoot, "native", "rust-worker"));
    const result = await withEnv(
      {
        CAUSORYN_ASSET_ROOT: assetRoot,
        CAUSORYN_RUST_TARGET_DIR: path.join(repo, ".rust-cache"),
        CAUSORYN_RUST_WORKER_DIR: undefined,
      },
      () =>
        analyzeRustWorkspace({
          workspaceId: "b2-refuse",
          workspaceRoot: repo,
          files: [{ path: "lib.rs", content: "pub fn a() {}\n" }],
        }),
    );
    expect(result.workerAvailable).toBe(false);
    expect(result.warnings.join("\n")).toContain("inside the analyzed workspace");
    expect(existsSync(path.join(repo, ".rust-cache"))).toBe(false);
  });

  const cargoAvailable = isCargoAvailable();
  it.skipIf(!cargoAvailable)(
    "hostile <repo>/.cargo/config.toml (build.rustc, linker, rustc-wrapper) and rust-toolchain.toml are never used when the package sits in <repo>/node_modules",
    async () => {
      const repo = tempDir("causoryn-b2-real-");
      const markerFile = path.join(tempDir("causoryn-b2-marker-"), "cargo-config.hit");
      plantHostileCargoConfig(repo, markerFile);
      const assetRoot = path.join(repo, "node_modules", "causoryn");
      stageMinimalRustCrate(path.join(assetRoot, "native", "rust-worker"));
      const cacheRoot = tempDir("causoryn-b2-real-cache-");
      const result = await withEnv(
        {
          CAUSORYN_ASSET_ROOT: assetRoot,
          CAUSORYN_RUST_TARGET_DIR: cacheRoot,
          CAUSORYN_RUST_WORKER_DIR: undefined,
        },
        () =>
          withCwdSearchUnmasked(repo, () =>
            analyzeRustWorkspace({
              workspaceId: "b2-real",
              workspaceRoot: repo,
              files: [{ path: "lib.rs", content: "pub fn a() {}\n" }],
            }),
          ),
      );
      expect(existsSync(markerFile)).toBe(false);
      expect(result.workerAvailable).toBe(true);
      expect(existsSync(path.join(cacheRoot, "debug", WORKER_BINARY_NAME))).toBe(true);
      expect(existsSync(path.join(assetRoot, "native", "rust-worker", "target"))).toBe(false);
    },
    300_000,
  );

  it.skipIf(!cargoAvailable)(
    "a cached worker binary tampered in place is not executed and the new pin is computed from freshly built bytes",
    async () => {
      const assetRoot = tempDir("causoryn-b4-asset-");
      stageMinimalRustCrate(path.join(assetRoot, "native", "rust-worker"));
      const cacheRoot = tempDir("causoryn-b4-cache-");
      const env = {
        CAUSORYN_ASSET_ROOT: assetRoot,
        CAUSORYN_RUST_TARGET_DIR: cacheRoot,
        CAUSORYN_RUST_WORKER_DIR: undefined,
      };
      const analyze = (id: string) =>
        withEnv(env, () =>
          analyzeRustWorkspace({ workspaceId: id, files: [{ path: "lib.rs", content: "pub fn a() {}\n" }] }),
        );
      const first = await analyze("b4-first");
      expect(first.workerAvailable).toBe(true);
      const cachedBin = path.join(cacheRoot, "debug", WORKER_BINARY_NAME);
      expect(existsSync(cachedBin)).toBe(true);

      // Overwrite the cached binary IN PLACE (same file), keeping the old pin.
      const tamperedBytes = Buffer.from("tampered-bytes-not-a-valid-executable");
      // Windows keeps the image locked until the killed worker has exited.
      for (let attempt = 0; ; attempt += 1) {
        try {
          writeFileSync(cachedBin, tamperedBytes);
          break;
        } catch (error) {
          const code = (error as NodeJS.ErrnoException).code;
          if ((code !== "EBUSY" && code !== "EPERM") || attempt >= 100) throw error;
          await new Promise((resolve) => setTimeout(resolve, 100));
        }
      }
      const tamperedSha = createHash("sha256").update(tamperedBytes).digest("hex");

      const second = await analyze("b4-second");
      expect(second.workerAvailable).toBe(true);
      const pin = JSON.parse(readFileSync(rustWorkerIntegrityPath(cachedBin), "utf8")) as { binarySha256: string };
      const actualSha = readRegularFileSha256NoFollow(cachedBin);
      expect(pin.binarySha256).not.toBe(tamperedSha);
      expect(actualSha).toBe(pin.binarySha256);
      expect(readFileSync(cachedBin).equals(tamperedBytes)).toBe(false);
    },
    300_000,
  );
});
