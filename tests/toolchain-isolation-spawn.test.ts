/**
 * Toolchain spawn hardening:
 * - every sidecar / cargo / taskkill child is started by ABSOLUTE path with a
 *   trusted cwd (Windows cwd-first executable search),
 * - the Rust worker is built from a staged copy of its crate in a
 *   Causoryn-controlled cache directory (ancestor `.cargo/config.toml` and
 *   `rust-toolchain.toml` of the analyzed repository are never read),
 * - a tampered cached worker binary is never re-pinned.
 */
