function createFakeChild(responseLine?: string): ChildProcess {
  const child = new EventEmitter() as unknown as ChildProcess;
  const stdout = new EventEmitter();
  const stderr = new EventEmitter();
  const stdin = new EventEmitter();
  const record = child as unknown as Record<string, unknown>;
  record["stdout"] = stdout;
  record["stderr"] = stderr;
  record["stdin"] = Object.assign(stdin, {
    write: () => true,
    end: () => {},
  });
  record["killed"] = false;
  record["exitCode"] = null;
  record["signalCode"] = null;
  record["kill"] = () => {
    record["killed"] = true;
    return true;
  };
  queueMicrotask(() => {
    if (responseLine !== undefined) {
      stdout.emit("data", Buffer.from(`${responseLine}\n`, "utf8"));
    } else {
      child.emit("exit", 0, null);
    }
  });
  return child;
}

async function withTemporaryEnv<T>(
  overrides: Readonly<Record<string, string | undefined>>,
  fn: () => Promise<T> | T,
): Promise<T> {
  const saved = new Map<string, string | undefined>();
  for (const key of Object.keys(overrides)) {
    saved.set(key, process.env[key]);
    const next = overrides[key];
    if (next === undefined) {
      delete process.env[key];
    } else {
      process.env[key] = next;
    }
  }
  try {
    return await fn();
  } finally {
    for (const [key, prev] of saved.entries()) {
      if (prev === undefined) {
        delete process.env[key];
      } else {
        process.env[key] = prev;
      }
    }
  }
}

async function withTemporaryCwd<T>(
  dir: string,
  fn: () => Promise<T> | T,
): Promise<T> {
  const prev = process.cwd();
  process.chdir(dir);
  try {
    return await fn();
  } finally {
    process.chdir(prev);
  }
}

function stageMinimalRustWorker(assetRoot: string): {
  readonly manifestPath: string;
  readonly workerDir: string;
} {
  const workerDir = path.join(assetRoot, "native", "rust-worker");
  const srcDir = path.join(workerDir, "src");
  mkdirSync(srcDir, { recursive: true });
  const manifestPath = path.join(workerDir, "Cargo.toml");
  writeFileSync(
    manifestPath,
    [
      "[package]",
      'name = "causoryn-rust-worker"',
      'version = "0.1.0"',
      'edition = "2021"',
      "",
      "[dependencies]",
      "",
    ].join("\n"),
    "utf8",
  );
  writeFileSync(
    path.join(workerDir, "Cargo.lock"),
    [
      "# This file is automatically @generated by Cargo.",
      "# It is not intended for manual editing.",
      "version = 4",
      "",
      "[[package]]",
      'name = "causoryn-rust-worker"',
      'version = "0.1.0"',
      "",
    ].join("\n"),
    "utf8",
  );
  writeFileSync(
    path.join(srcDir, "main.rs"),
    [
      "use std::io::{self, BufRead, Write};",
      "",
      "fn extract_id(line: &str) -> String {",
      '    let needle = "\\"id\\":\\"";',
      "    if let Some(start) = line.find(needle) {",
      "        let (_, rest) = line.split_at(start + needle.len());",
      "        if let Some(end) = rest.find('\"') {",
      "            let (id_slice, _) = rest.split_at(end);",
      "            return id_slice.to_string();",
      "        }",
      "    }",
      '    String::from("analyze:unknown")',
      "}",
      "",
      "fn main() {",
      "    let stdin = io::stdin();",
      "    let mut first_line = String::new();",
      "    let _ = stdin.lock().read_line(&mut first_line);",
      "    let req_id = extract_id(&first_line);",
      "    let response = format!(",
      '        "{{\\"id\\":\\"{}\\",\\"protocolVersion\\":\\"1\\",\\"status\\":\\"ready\\",\\"coverageRatio\\":1.0,\\"capabilities\\":{{\\"astParse\\":true,\\"symbolResolution\\":true,\\"containsEdges\\":true,\\"callEdges\\":true,\\"importEdges\\":false,\\"routeDetection\\":\\"rust-attribute-macro-route-pattern\\",\\"frameworkLinkers\\":false}},\\"unsupportedConstructs\\":[],\\"warnings\\":[],\\"diagnostics\\":[],\\"nodes\\":[],\\"edges\\":[],\\"evidence\\":[]}}\\n",',
      "        req_id",
      "    );",
      "    let _ = io::stdout().write_all(response.as_bytes());",
      "    let _ = io::stdout().flush();",
      "}",
      "",
    ].join("\n"),
    "utf8",
  );
  return { manifestPath, workerDir };
}

describe("Task 1.1: Sidecar IPC hardening", () => {
  it("always sets shell:false and windowsHide:true on spawn", async () => {
    const captured: SidecarSpawnOptions[] = [];
    const outcome = await runLineJsonWorker({
      command: path.join(os.tmpdir(), "worker-bin"),
      args: [],
      env: { PATH: "/bin" },
      cwd: REPO_ROOT,
      requestPayload: { id: "ipc-hardening" },
      requestTimeoutMs: 5_000,
      spawnProcess: (_cmd, _args, opts) => {
        captured.push(opts);
        return createFakeChild('{"ok":true}');
      },
    });
    expect(outcome.status).toBe("ok");
    expect(captured).toHaveLength(1);
    expect(captured[0]?.shell).toBe(false);
    expect(captured[0]?.windowsHide).toBe(true);
    expect(captured[0]?.cwd).toBe(REPO_ROOT);
  });

  it("rejects empty or whitespace-only cwd without spawning", async () => {
    let spawned = false;
    for (const badCwd of ["", "   ", "\t\n"]) {
      const outcome = await runLineJsonWorker({
        command: path.join(os.tmpdir(), "worker-bin"),
        args: [],
        env: { PATH: "/bin" },
        cwd: badCwd,
        requestPayload: { id: "bad-cwd" },
        requestTimeoutMs: 5_000,
        spawnProcess: () => {
          spawned = true;
          return createFakeChild('{"ok":true}');
        },
      });
      expect(outcome.status).toBe("unavailable");
      expect(outcome.detail).toContain("cwd");
    }
    expect(spawned).toBe(false);
  });
});

